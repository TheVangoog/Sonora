// Tuner accuracy on pure sine tones: error of the raw YIN reading (no smoothing) in cents.
// Each tone is measured in many frames with different starting phases, like
// frames cut at random moments from the built-in generator.
// Usage: node scripts/measure-tuner.ts  → docs/results/tuner-yin-<date>.md
import { writeFileSync } from "node:fs";
import { ToneDetector, tunerFrameSize, YIN_THRESHOLD } from "../src/audio/pitch.ts";

const TONES: [string, number][] = [
  ["test tone 110.00 Hz", 110],
  ["test tone 83.37 Hz", 83.37],
  ["test tone 194.87 Hz", 194.87],
  ["E2 (6th string)", 82.4069],
  ["A2 (5th string)", 110],
  ["D3 (4th string)", 146.8324],
  ["G3 (3rd string)", 195.9977],
  ["B3 (2nd string)", 246.9417],
  ["E4 (1st string)", 329.6276],
];
const SAMPLE_RATES = [44100, 48000];
const FRAMES = 200;
const AMPLITUDE = 0.2; // the generator's default level

let seed = 20261115;
function random() {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 2 ** 32;
}

type Row = { label: string; frequency: number; rate: number; detected: number; mean: number; meanAbs: number; maxAbs: number; ms: number };
const rows: Row[] = [];
const detector = new ToneDetector();

for (const rate of SAMPLE_RATES) {
  const size = tunerFrameSize(rate);
  for (const [label, frequency] of TONES) {
    const errors: number[] = [];
    let elapsed = 0;
    for (let f = 0; f < FRAMES; f++) {
      const phase = random() * 2 * Math.PI;
      const frame = Float32Array.from({ length: size }, (_, i) =>
        AMPLITUDE * Math.sin((2 * Math.PI * frequency * i) / rate + phase),
      );
      const start = performance.now();
      const reading = detector.analyze(frame, rate);
      elapsed += performance.now() - start;
      if (reading.status === "detected") errors.push(1200 * Math.log2(reading.frequency / frequency));
    }
    const abs = errors.map(Math.abs);
    rows.push({
      label,
      frequency,
      rate,
      detected: errors.length,
      mean: errors.reduce((a, b) => a + b, 0) / (errors.length || 1),
      meanAbs: abs.reduce((a, b) => a + b, 0) / (abs.length || 1),
      maxAbs: abs.length ? Math.max(...abs) : NaN,
      ms: elapsed / FRAMES,
    });
  }
}

const date = new Date().toISOString().slice(0, 10);
const fmt = (n: number, digits = 4) => (Number.isFinite(n) ? (Math.abs(n) < 0.5 * 10 ** -digits ? 0 : n).toFixed(digits) : "—");
const lines = [
  `# Tuner accuracy, YIN (${date})`,
  "",
  `Pure sine tones, amplitude ${AMPLITUDE}, ${FRAMES} frames per tone with random starting phase.`,
  `Raw ToneDetector reading (YIN, threshold ${YIN_THRESHOLD}, parabolic interpolation), before the display smoother.`,
  `Frame: ${SAMPLE_RATES.map((r) => `${tunerFrameSize(r)} samples at ${r} Hz`).join(", ")}.`,
  "Error = 1200·log2(measured / true) in cents. Generated by `node scripts/measure-tuner.ts` (Node " + process.version + ").",
  "",
  "| Tone | True Hz | Sample rate | Detected | Mean error (signed) | Mean abs. error | Max abs. error | Time per frame |",
  "|---|---|---|---|---|---|---|---|",
  ...rows.map(
    (r) =>
      `| ${r.label} | ${r.frequency} | ${r.rate} | ${r.detected}/${FRAMES} | ${fmt(r.mean)} ¢ | ${fmt(r.meanAbs)} ¢ | ${fmt(r.maxAbs)} ¢ | ${fmt(r.ms, 2)} ms |`,
  ),
  "",
];
const worst = Math.max(...rows.map((r) => r.maxAbs));
lines.push(`Largest error over all tones and sample rates: ${fmt(worst)} cents (goal: ±5 cents).`, "");
const out = `docs/results/tuner-yin-${date}.md`;
writeFileSync(out, lines.join("\n"));
console.log(lines.join("\n"));
console.log("written", out);
